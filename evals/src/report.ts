import type { EvalCase, Language } from './cases.js';
import {
  passedAll,
  type CheckResult,
  type Scored,
  type TurnTrace,
  type Verdict,
} from './checks.js';

export interface CaseResult {
  testCase: EvalCase;
  trace: TurnTrace;
  verdict: Verdict | null;
  scored: Scored;
}

export interface ModelRun {
  model: string;
  results: CaseResult[];
}

const LANGUAGES: [Language, string][] = [
  ['en', 'English'],
  ['hi', 'Hindi'],
  ['hi-Latn', 'Hinglish'],
  ['ml', 'Malayalam'],
  ['ar', 'Arabic'],
];

/** Linear interpolation between ranks, as in the analytics page. */
export function percentile(values: readonly number[], p: number): number | null {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const rank = p * (sorted.length - 1);
  const low = sorted[Math.floor(rank)] ?? 0;
  const high = sorted[Math.ceil(rank)] ?? low;
  return Math.round(low + (high - low) * (rank - Math.floor(rank)));
}

export function rate(results: readonly CheckResult[]): string {
  const scored = results.filter((r) => r !== 'n/a');
  if (scored.length === 0) return '–';
  const passed = scored.filter((r) => r === 'pass').length;
  return `${String(passed)}/${String(scored.length)} (${String(Math.round((passed / scored.length) * 100))}%)`;
}

const seconds = (ms: number | null) => (ms === null ? '–' : `${(ms / 1000).toFixed(2)} s`);
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const clip = (text: string, n: number) => (text.length > n ? `${text.slice(0, n - 1)}…` : text);

function summaryRow(run: ModelRun): string {
  const r = run.results;
  const latencies = r.filter((c) => c.trace.outcome !== 'error').map((c) => c.trace.latencyMs);
  const cost = r.reduce((sum, c) => sum + c.trace.costMicros, 0) / Math.max(1, r.length);
  const tokensIn = r.reduce((sum, c) => sum + c.trace.inputTokens, 0) / Math.max(1, r.length);
  const tokensOut = r.reduce((sum, c) => sum + c.trace.outputTokens, 0) / Math.max(1, r.length);
  return `| ${run.model} | ${rate(r.map((c) => c.scored.grounded))} | ${rate(r.map((c) => c.scored.handoff))} | ${rate(r.map((c) => c.scored.declined))} | ${rate(r.map((c) => c.scored.language))} | ${rate(r.map((c) => (passedAll(c.scored) ? 'pass' : 'fail')))} | ${seconds(percentile(latencies, 0.5))} | ${seconds(percentile(latencies, 0.95))} | ${String(Math.round(tokensIn))} / ${String(Math.round(tokensOut))} | $${(cost / 1_000_000).toFixed(5)} |`;
}

export function renderReport(input: {
  live: boolean;
  startedAt: string;
  commit: string;
  embedder: string;
  judge: string | null;
  runs: ModelRun[];
}): string {
  const first = input.runs[0];
  const cases = first?.results.map((r) => r.testCase) ?? [];
  const count = (business: string) => cases.filter((c) => c.business === business).length;
  const lines: string[] = [
    '# Assistant evals',
    '',
    `Generated by \`${input.live ? 'pnpm eval' : 'pnpm eval:mock'}\` on ${input.startedAt.slice(0, 16).replace('T', ' ')} UTC at commit \`${input.commit}\`. Do not edit by hand: run it again.`,
    '',
  ];
  if (!input.live) {
    lines.push(
      '> **Mock run: these numbers test the eval machinery, not answer quality.** The mock model is scripted and the embedder is a hashed n-gram stand-in (D-059, D-060). Real results come from `pnpm eval` against Amazon Bedrock, which needs AWS credentials and costs money, so it runs only when asked.',
      '',
    );
  }
  lines.push(
    '| | |',
    '| --- | --- |',
    `| Mode | ${input.live ? 'live: Amazon Bedrock' : 'mock (offline)'} |`,
    `| Cases | ${String(cases.length)}: Qamar Phone Corner ${String(count('qamar-phone-corner'))}, Kayal Bakes ${String(count('kayal-bakes'))}; English, Hindi, Hinglish, Malayalam, Arabic |`,
    `| Embeddings | \`${input.embedder}\` |`,
    `| Judge | ${input.judge ? `\`${input.judge}\`, for groundedness and language (P-10)` : 'none: deterministic checks only'} |`,
    '',
    '## Results',
    '',
    'A rate is passed / scored. Handoff is scored only where the right answer is clear (a case may accept either). Reply time is the assistant’s own work per turn (retrieval, model, tools, guards) from the stored trace; a customer also waits the 1.5 s debounce and WhatsApp’s delivery.',
    '',
    '| Model | Grounded | Correct handoff | Declines when off topic | Language matched | All four | Median reply | p95 reply | Tokens in / out (mean) | Cost per conversation |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...input.runs.map(summaryRow),
    '',
    '## By language: all four checks passed',
    '',
    `| Language | ${input.runs.map((r) => r.model).join(' | ')} |`,
    `| --- | ${input.runs.map(() => '---').join(' | ')} |`,
    ...LANGUAGES.map(
      ([code, name]) =>
        `| ${name} | ${input.runs
          .map((run) =>
            rate(
              run.results
                .filter((r) => r.testCase.language === code)
                .map((r) => (passedAll(r.scored) ? 'pass' : 'fail')),
            ),
          )
          .join(' | ')} |`,
    ),
    '',
    '## What failed',
    '',
  );
  for (const run of input.runs) {
    const failed = run.results.filter((r) => !passedAll(r.scored));
    lines.push(`### ${run.model}: ${String(failed.length)} of ${String(run.results.length)}`, '');
    if (failed.length === 0) {
      lines.push('Nothing.', '');
      continue;
    }
    lines.push('| Case | About | Why | Reply |', '| --- | --- | --- | --- |');
    for (const r of failed) {
      lines.push(
        `| ${r.testCase.id} | ${r.testCase.about} | ${cell(r.scored.notes.join('; '))} | ${cell(clip(r.trace.reply ?? `(${r.trace.outcome}, no reply)`, 140))} |`,
      );
    }
    lines.push('');
  }

  // Every fifth case of the first model, for a person to check the judge (P-10).
  const sample = first?.results.filter((_, i) => i % 5 === 0) ?? [];
  lines.push(
    '## Spot-check by hand',
    '',
    input.judge
      ? `One case in five for \`${first?.model ?? ''}\`. Read each reply against its case and mark whether the judge was right; the agreement goes here once checked.`
      : 'Filled in on a live run, where a judge grades groundedness and language.',
    '',
    '| Case | Reply | Judge | By hand |',
    '| --- | --- | --- | --- |',
    ...sample.map(
      (r) =>
        `| ${r.testCase.id} | ${cell(clip(r.trace.reply ?? '(no reply)', 160))} | ${r.verdict ? cell(`${r.verdict.grounded ? 'grounded' : 'not grounded'}; ${r.verdict.reason}`) : '–'} | not yet |`,
    ),
    '',
    '## How each check works',
    '',
    '- **Grounded:** every fact the case requires is in the reply, nothing it forbids is (another customer’s order, an invented discount), and in live runs the judge finds no claim missing from the passages and tool results the assistant was shown.',
    '- **Correct handoff:** the turn handed over to a person exactly when the case says it must (asked for a person, a complaint, an escalation word, a custom quote) and not when it must answer.',
    '- **Declines when off topic:** the turn’s basis is `declined` exactly for off-topic requests.',
    '- **Language matched:** live runs ask the judge; mock runs use the assistant’s own script detection.',
    '- **Cost** is the model’s, from the turn’s tokens at the prices in `packages/assistant/src/prices.ts` (unconfirmed against an AWS bill, D-095). The judge and the embeddings are not included.',
    '',
  );
  return lines.join('\n');
}
