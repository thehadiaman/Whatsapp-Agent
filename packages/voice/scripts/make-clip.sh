#!/usr/bin/env bash
# Regenerates src/clip.ts: the short OGG/Opus clip the mock text-to-speech
# returns (brief §5). Two soft tones, 1.2 s, mono, 48 kHz, Opus at 16 kb/s,
# the format WhatsApp needs for a voice message. Needs ffmpeg with libopus.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i "sine=frequency=262:duration=1.2" \
  -f lavfi -i "sine=frequency=392:duration=1.2" \
  -filter_complex "[0][1]amix=inputs=2,volume=0.25,afade=t=in:d=0.15,afade=t=out:st=0.9:d=0.3,aresample=48000" \
  -ac 1 -c:a libopus -b:a 16k -application voip \
  -map_metadata -1 -fflags +bitexact -flags:a +bitexact "$tmp/clip.ogg"
{
  echo '// Generated by scripts/make-clip.sh. Do not edit.'
  echo '/** The mock voice: 1.2 s of two soft tones, OGG/Opus, mono, 48 kHz. */'
  printf "export const MOCK_CLIP_BASE64 =\n  '%s';\n" "$(base64 -w0 "$tmp/clip.ogg")"
} > src/clip.ts
echo "wrote src/clip.ts ($(wc -c < "$tmp/clip.ogg") bytes of audio)"
